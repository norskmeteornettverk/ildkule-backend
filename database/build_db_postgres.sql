CREATE TABLE IF NOT EXISTS event_res_entry (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  event_id INTEGER NOT NULL,
  line_no INTEGER NOT NULL,
  entry_type VARCHAR(20) NOT NULL,
  label VARCHAR(20) NULL,
  long1 REAL NULL,
  lat1 REAL NULL,
  long2 REAL NULL,
  lat2 REAL NULL,
  height REAL NULL,
  raw_line VARCHAR(500) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uq_event_res_entry_line UNIQUE (event_id, line_no),
  CONSTRAINT event_res_entry_ibfk_1
    FOREIGN KEY (event_id)
    REFERENCES event (id)
    ON DELETE CASCADE
    ON UPDATE NO ACTION
);
CREATE INDEX IF NOT EXISTS event_res_entry_event_id_idx ON event_res_entry (event_id);

CREATE TABLE IF NOT EXISTS observation_trail_point (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  observation_id INTEGER NOT NULL,
  frame_index INTEGER NOT NULL,
  pixel_x REAL NULL,
  pixel_y REAL NULL,
  event_timestamp_us BIGINT NULL,
  coord_long REAL NULL,
  coord_lat REAL NULL,
  ams_coord_long REAL NULL,
  ams_coord_lat REAL NULL,
  centroid_coord_long REAL NULL,
  centroid_coord_lat REAL NULL,
  centroid2_coord_long REAL NULL,
  centroid2_coord_lat REAL NULL,
  gnomonic_x REAL NULL,
  gnomonic_y REAL NULL,
  brightness REAL NULL,
  dct REAL NULL,
  size REAL NULL,
  frame_brightness REAL NULL,
  PRIMARY KEY (id),
  CONSTRAINT uq_observation_trail_point_frame UNIQUE (observation_id, frame_index),
  CONSTRAINT observation_trail_point_ibfk_1
    FOREIGN KEY (observation_id)
    REFERENCES observation_cam_data (id)
    ON DELETE CASCADE
    ON UPDATE NO ACTION
);
CREATE INDEX IF NOT EXISTS observation_trail_point_observation_id_idx ON observation_trail_point (observation_id);

CREATE TABLE IF NOT EXISTS log_station (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  station_name VARCHAR(255) NOT NULL,
  code VARCHAR(255) NOT NULL,
  log_time TIMESTAMP NOT NULL,
  created_at TIMESTAMP NOT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS user_review (
  user_id INTEGER NOT NULL,
  confirmed SMALLINT NULL,
  event_id INTEGER NOT NULL,
  PRIMARY KEY (user_id, event_id),
  CONSTRAINT fk_users_has_observation_cam_data_users1
    FOREIGN KEY (user_id)
    REFERENCES "user" (id)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
  CONSTRAINT fk_user_review_event1
    FOREIGN KEY (event_id)
    REFERENCES event (id)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);
CREATE INDEX IF NOT EXISTS fk_users_has_observation_cam_data_users1_idx ON user_review (user_id);
CREATE INDEX IF NOT EXISTS fk_user_review_event1_idx ON user_review (event_id);
