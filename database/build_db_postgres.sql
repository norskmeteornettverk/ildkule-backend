-- -----------------------------------------------------
-- PostgreSQL bootstrap schema for Ildkule
-- Mirrors the active MySQL bootstrap surface as closely as possible.
-- -----------------------------------------------------

DROP TABLE IF EXISTS user_review CASCADE;
DROP TABLE IF EXISTS log_station CASCADE;
DROP TABLE IF EXISTS observation_trail_point CASCADE;
DROP TABLE IF EXISTS event_res_entry CASCADE;
DROP TABLE IF EXISTS observation_cam_data CASCADE;
DROP TABLE IF EXISTS event CASCADE;
DROP TABLE IF EXISTS cam CASCADE;
DROP TABLE IF EXISTS station CASCADE;
DROP TABLE IF EXISTS manual_input_observation CASCADE;
DROP TABLE IF EXISTS "user" CASCADE;

CREATE TABLE IF NOT EXISTS "user" (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  username VARCHAR(255) NULL UNIQUE,
  password VARCHAR(255) NULL,
  role VARCHAR(255) DEFAULT 'ROLE_USER',
  user_level VARCHAR(255) DEFAULT '0',
  tutorial_completed BOOLEAN DEFAULT FALSE,
  confirmed BOOLEAN DEFAULT FALSE,
  confirm_token VARCHAR(1000),
  password_reset_token VARCHAR(1000),
  password_reset_request_time TIMESTAMP NULL,
  create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time TIMESTAMP NULL,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS manual_input_observation (
  id INTEGER NOT NULL,
  latitude REAL NULL,
  longitude REAL NULL,
  date_time TIMESTAMP NULL,
  first_recorded_direction VARCHAR(45) NULL,
  first_recorded_altitude VARCHAR(45) NULL,
  last_recorded_direction VARCHAR(45) NULL,
  last_recorded_altitude VARCHAR(45) NULL,
  duration REAL NULL,
  color VARCHAR(45) NULL,
  brightness VARCHAR(45) NULL,
  description VARCHAR(280) NULL,
  image_file VARCHAR(45) NULL,
  users_id INTEGER NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_manual_input_observation_users
    FOREIGN KEY (users_id)
    REFERENCES "user" (id)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
);
CREATE INDEX IF NOT EXISTS fk_manual_input_observation_users_idx ON manual_input_observation (users_id);

CREATE TABLE IF NOT EXISTS station (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  station_name VARCHAR(100) NOT NULL UNIQUE,
  created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS cam (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  station_id INTEGER NOT NULL,
  cam_name VARCHAR(100) NOT NULL,
  created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT unique_cam_cam_name_station_id UNIQUE (cam_name, station_id),
  CONSTRAINT cam_ibfk_1
    FOREIGN KEY (station_id)
    REFERENCES station (id)
);
CREATE INDEX IF NOT EXISTS cam_station_id_idx ON cam (station_id);

CREATE TABLE IF NOT EXISTS event (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  datetimetag VARCHAR(32) NOT NULL,
  location VARCHAR(100) NULL,
  create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  track_startheight REAL NULL,
  track_endheight REAL NULL,
  track_groundtrack REAL NULL,
  track_course REAL NULL,
  track_incidence REAL NULL,
  track_speed REAL NULL,
  track_speed_source VARCHAR(100) NULL,
  track_startlat REAL NULL,
  track_startlong REAL NULL,
  track_endlat REAL NULL,
  track_endlong REAL NULL,
  fit_error REAL NULL,
  fit_quality REAL NULL,
  radiant_ra REAL NULL,
  radiant_dec REAL NULL,
  radiant_ecl_long REAL NULL,
  radiant_ecl_lat REAL NULL,
  radiant_shower VARCHAR(100) NULL,
  radiant_zenith_attractor VARCHAR(100) NULL,
  timestamp VARCHAR(100) NULL,
  date TIMESTAMP NULL,
  camera_confirmed SMALLINT DEFAULT NULL,
  user_confirmed SMALLINT DEFAULT NULL,
  first_seen_at TIMESTAMP NOT NULL,
  last_seen_at TIMESTAMP NULL,
  deleted_at TIMESTAMP NULL,
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  deletion_reason VARCHAR(50) NULL,
  PRIMARY KEY (id),
  CONSTRAINT unique_event_datetimetag UNIQUE (datetimetag)
);
CREATE INDEX IF NOT EXISTS event_date_idx ON event (date DESC, id DESC);
CREATE INDEX IF NOT EXISTS event_public_date_idx
  ON event (date DESC, id DESC)
  WHERE is_deleted = FALSE AND (user_confirmed IS NULL OR user_confirmed <> 0);

