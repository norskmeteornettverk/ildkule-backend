  trail_frames INTEGER NULL,
  trail_duration REAL NULL,
  trail_slope REAL NULL,
  trail_offset REAL NULL,
  trail_speed REAL NULL,
  trail_correlation REAL NULL,
  trail_positions TEXT NULL,
  trail_timestamps TEXT NULL,
  trail_coordinates TEXT NULL,
  trail_ams_coords TEXT NULL,
