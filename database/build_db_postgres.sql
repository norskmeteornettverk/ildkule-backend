  config_swidth INTEGER NULL,
  config_sheight INTEGER NULL,
  config_swdec INTEGER NULL,
  config_downscale_thr INTEGER NULL,
  config_mintrail_sec REAL NULL,
  config_maxtrail_sec REAL NULL,
  config_mintrail REAL NULL,
  config_maxtrail REAL NULL,
  config_minspeed REAL NULL,
  config_maxspeed REAL NULL,
  config_minspeed_kms REAL NULL,
  config_maxspeed_kms REAL NULL,
  config_leveltest INTEGER NULL,
  config_numspots INTEGER NULL,
  config_brightness INTEGER NULL,
  config_flash_thr REAL NULL,
  config_lookahead INTEGER NULL,
  config_exit INTEGER NULL,
  config_peak REAL NULL,
  config_filter INTEGER NULL,
  config_dct_threshold REAL NULL,
  config_correlation REAL NULL,
  config_spacing_correlation REAL NULL,
  config_gnomonic_correlation REAL NULL,
  config_nothreads INTEGER NULL,
  config_lastreport_ts BIGINT NULL,
